import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const repoRoot = path.resolve(__dirname, '..', '..')
const sourcePath = path.join(repoRoot, 'server', 'internal', 'server', 'feature_intent_terms.json')
const targetPath = path.join(repoRoot, 'web', 'src', 'composables', 'featureIntentTerms.generated.ts')

const jsonRaw = await readFile(sourcePath, 'utf8')
const terms = JSON.parse(jsonRaw)

const output = `/* eslint-disable */
// Code generated by web/scripts/sync-feature-intent-terms.mjs. DO NOT EDIT.

export interface FeatureIntentTerms {
  deepResearchExplicit: string[]
  deepResearchActions: string[]
  deepResearchTargets: string[]
  deepResearchNegations: string[]
  agentModeExplicit: string[]
  agentModeActions: string[]
  agentModeTargets: string[]
  agentModeNegations: string[]
  definitionPrefixes: string[]
}

export const featureIntentTerms: FeatureIntentTerms = ${JSON.stringify(
  {
    deepResearchExplicit: terms.deep_research_explicit || [],
    deepResearchActions: terms.deep_research_actions || [],
    deepResearchTargets: terms.deep_research_targets || [],
    deepResearchNegations: terms.deep_research_negations || [],
    agentModeExplicit: terms.agent_mode_explicit || [],
    agentModeActions: terms.agent_mode_actions || [],
    agentModeTargets: terms.agent_mode_targets || [],
    agentModeNegations: terms.agent_mode_negations || [],
    definitionPrefixes: terms.definition_prefixes || [],
  },
  null,
  2,
)}\n`

await writeFile(targetPath, output, 'utf8')
console.log(`synced feature intent terms -> ${targetPath}`)
