export function mergeHarnessLocale<T extends Record<string, unknown>>(
  localeKey: LocaleKey,
  messages: T
): T {
  const patch = mergeLocaleNodes(
    baseHarnessPatch as LocaleNode,
    (localeHarnessOverrides[localeKey] ?? {}) as LocaleNode
  )
  const currentHarness = (messages.harness ?? {}) as LocaleNode

  return {
    ...messages,
    harness: mergeLocaleNodes(patch, currentHarness),
  } as T
}
