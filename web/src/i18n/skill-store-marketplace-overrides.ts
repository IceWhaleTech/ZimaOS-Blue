type MessageTree = Record<string, any>

function mergeMarketplace(base: MessageTree, overrides: MessageTree): MessageTree {
  const result: MessageTree = { ...base }
  for (const [key, value] of Object.entries(overrides)) {
    if (
      value &&
      typeof value === 'object' &&
      !Array.isArray(value) &&
      result[key] &&
      typeof result[key] === 'object' &&
      !Array.isArray(result[key])
    ) {
      result[key] = mergeMarketplace(result[key], value)
      continue
    }
    result[key] = value
  }
  return result
}

function wrapMarketplace(overrides: MessageTree) {
  return {
    skillStore: {
      marketplace: mergeMarketplace(enUSMarketplace, overrides),
    },
  }
}

