type HarnessV3Section = keyof typeof harnessV3SectionKeys

const createHarnessLocaleMessages = (
  sections: Partial<Record<HarnessV3Section, string[]>>
): LocaleMessages => {
  const harness: Record<string, Record<string, string>> = {}

  for (const section of Object.keys(sections) as HarnessV3Section[]) {
    const keys = harnessV3SectionKeys[section]
    const values = sections[section]

    if (!values) {
      continue
    }

    if (values.length !== keys.length) {
      throw new Error(
        `Expected ${keys.length} values for harness section "${section}" but received ${values.length}.`
      )
    }

    harness[section] = Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<
      string,
      string
    >
  }

  return { harness } as LocaleMessages
}

