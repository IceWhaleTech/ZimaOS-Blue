function zipArray(keys: readonly string[], values?: readonly (string | undefined)[]) {
  const out: Record<string, string> = {}
  if (!values) return out
  for (let index = 0; index < keys.length && index < values.length; index += 1) {
    const key = keys[index]
    const value = values[index]
    if (key && value !== undefined) {
      out[key] = value
    }
  }
  return out
}

function buildLocaleOverrides(pack: {
  sharedNames?: readonly (string | undefined)[]
  skillDescriptions?: readonly (string | undefined)[]
  toolOnlyNames?: readonly (string | undefined)[]
  toolDescriptions?: readonly (string | undefined)[]
  skillUI?: readonly (string | undefined)[]
  toolParams?: readonly (string | undefined)[]
}) {
  const sharedNames = zipArray(sharedNameMap.map(([key]) => key), pack.sharedNames)
  const skillDescriptions = zipArray(
    skillDescriptionMap.map(([key]) => key),
    pack.skillDescriptions,
  )
  const toolOnlyNames = zipArray(toolOnlyNameMap.map(([key]) => key), pack.toolOnlyNames)
  const toolDescriptions = zipArray(
    toolDescriptionMap.map(([key]) => key),
    pack.toolDescriptions,
  )
  const skillUI = zipArray(skillUIKeys, pack.skillUI)
  const toolParams = zipArray(toolParamKeys, pack.toolParams)

  const builtin: Record<string, Record<string, string>> = {}
  for (const [dataKey, skillKey] of sharedNameMap) {
    const name = sharedNames[dataKey]
    if (!name) continue
    builtin[skillKey] = { ...(builtin[skillKey] || {}), name }
  }
  for (const [dataKey, skillKey] of skillDescriptionMap) {
    const description = skillDescriptions[dataKey]
    if (!description) continue
    builtin[skillKey] = { ...(builtin[skillKey] || {}), description }
  }

  const toolNames: Record<string, string> = {}
  for (const [dataKey, , toolKey] of sharedNameMap) {
    const name = sharedNames[dataKey]
    if (name) toolNames[toolKey] = name
  }
  for (const [dataKey, toolKey] of toolOnlyNameMap) {
    const name = toolOnlyNames[dataKey]
    if (name) toolNames[toolKey] = name
  }
  for (const [toolKey, brandName] of Object.entries({
    discord: 'Discord',
    github: 'GitHub',
    notion: 'Notion',
    slack: 'Slack',
    docker: 'Docker',
  })) {
    if (!toolNames[toolKey]) {
      toolNames[toolKey] = brandName
    }
  }
  if (!toolNames.reminders && sharedNames.reminder) {
    toolNames.reminders = sharedNames.reminder
  }

  const builtToolDescriptions: Record<string, string> = {}
  for (const [dataKey, toolKey] of toolDescriptionMap) {
    const description = toolDescriptions[dataKey]
    if (description) builtToolDescriptions[toolKey] = description
  }

  const skillsBlock =
    Object.keys(builtin).length > 0 || Object.keys(skillUI).length > 0
      ? {
          builtin,
          ...(skillUI.noContent
            ? {
                noContent: skillUI.noContent,
              }
            : {}),
          ...(skillUI.allStatus
            ? {
                filters: {
                  allStatus: skillUI.allStatus,
                },
              }
            : {}),
          ...((skillUI.emptyTitle || skillUI.emptyDescription)
            ? {
                empty: {
                  ...(skillUI.emptyTitle ? { title: skillUI.emptyTitle } : {}),
                  ...(skillUI.emptyDescription ? { description: skillUI.emptyDescription } : {}),
                },
              }
            : {}),
          ...((skillUI.detailEmptyTitle ||
          skillUI.detailEmptyDescription ||
          skillUI.required ||
          skillUI.labelId ||
          skillUI.labelVersion ||
          skillUI.labelAuthor ||
          skillUI.labelCategory ||
          skillUI.labelBuiltin ||
          skillUI.labelCategories ||
          skillUI.sectionParameters ||
          skillUI.sectionInputs ||
          skillUI.sectionOutputs ||
          skillUI.sectionDocumentation ||
          skillUI.sectionFrontmatter)
            ? {
                detail: {
                  ...(skillUI.detailEmptyTitle ? { emptyTitle: skillUI.detailEmptyTitle } : {}),
                  ...(skillUI.detailEmptyDescription
                    ? { emptyDescription: skillUI.detailEmptyDescription }
                    : {}),
                  ...(skillUI.required ? { required: skillUI.required } : {}),
                  labels: {
                    ...(skillUI.labelId ? { id: skillUI.labelId } : {}),
                    ...(skillUI.labelVersion ? { version: skillUI.labelVersion } : {}),
                    ...(skillUI.labelAuthor ? { author: skillUI.labelAuthor } : {}),
                    ...(skillUI.labelCategory ? { category: skillUI.labelCategory } : {}),
                    ...(skillUI.labelBuiltin ? { builtin: skillUI.labelBuiltin } : {}),
                    ...(skillUI.labelCategories ? { categories: skillUI.labelCategories } : {}),
                  },
                  sections: {
                    ...(skillUI.sectionParameters ? { parameters: skillUI.sectionParameters } : {}),
                    ...(skillUI.sectionInputs ? { inputs: skillUI.sectionInputs } : {}),
                    ...(skillUI.sectionOutputs ? { outputs: skillUI.sectionOutputs } : {}),
                    ...(skillUI.sectionDocumentation
                      ? { documentation: skillUI.sectionDocumentation }
                      : {}),
                    ...(skillUI.sectionFrontmatter ? { frontmatter: skillUI.sectionFrontmatter } : {}),
                  },
                },
              }
            : {}),
          ...((skillUI.depsTitle ||
          skillUI.depsEligible ||
          skillUI.depsNotEligible ||
          skillUI.depsMissing ||
          skillUI.depsInstall ||
          skillUI.depsInstalling ||
          skillUI.depsInstallSuccess ||
          skillUI.depsInstallFailed)
            ? {
                deps: {
                  ...(skillUI.depsTitle ? { title: skillUI.depsTitle } : {}),
                  ...(skillUI.depsEligible ? { eligible: skillUI.depsEligible } : {}),
                  ...(skillUI.depsNotEligible ? { notEligible: skillUI.depsNotEligible } : {}),
                  ...(skillUI.depsMissing ? { missing: skillUI.depsMissing } : {}),
                  ...(skillUI.depsInstall ? { install: skillUI.depsInstall } : {}),
                  ...(skillUI.depsInstalling ? { installing: skillUI.depsInstalling } : {}),
                  ...(skillUI.depsInstallSuccess
                    ? { installSuccess: skillUI.depsInstallSuccess }
                    : {}),
                  ...(skillUI.depsInstallFailed
                    ? { installFailed: skillUI.depsInstallFailed }
                    : {}),
                },
              }
            : {}),
        }
      : undefined

  const toolsBlock =
    Object.keys(toolNames).length > 0 ||
    Object.keys(builtToolDescriptions).length > 0 ||
    Object.keys(toolParams).length > 0
      ? {
          ...(Object.keys(toolNames).length > 0 ? { names: toolNames } : {}),
          ...(Object.keys(builtToolDescriptions).length > 0
            ? { descriptions: builtToolDescriptions }
            : {}),
          ...(Object.keys(toolParams).length > 0 ? { params: toolParams } : {}),
        }
      : undefined

  return {
    ...(skillsBlock ? { skills: skillsBlock } : {}),
    ...(toolsBlock ? { tools: toolsBlock } : {}),
  }
}

