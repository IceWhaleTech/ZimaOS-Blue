func officeExcelDateSerial(value interface{}, withTime bool) (string, bool) {
	switch typed := value.(type) {
	case string:
		text := strings.TrimSpace(typed)
		if text == "" {
			return "", false
		}
		layouts := []string{
			time.RFC3339,
			"2006-01-02 15:04:05",
			"2006-01-02 15:04",
			"2006-01-02",
		}
		for _, layout := range layouts {
			ts, err := time.Parse(layout, text)
			if err != nil {
				continue
			}
			return officeTimeToExcelSerial(ts, withTime), true
		}
	case time.Time:
		return officeTimeToExcelSerial(typed, withTime), true
	}
	return "", false
}

func officeTimeToExcelSerial(ts time.Time, withTime bool) string {
	base := time.Date(1899, 12, 30, 0, 0, 0, 0, time.UTC)
	ts = ts.UTC()
	if !withTime {
		ts = time.Date(ts.Year(), ts.Month(), ts.Day(), 0, 0, 0, 0, time.UTC)
	}
	return officeNumericXMLValue(ts.Sub(base).Hours() / 24)
}

