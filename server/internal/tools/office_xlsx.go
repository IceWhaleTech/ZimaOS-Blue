func officeUniqueSheetName(raw string, used map[string]int) string {
	base := officeSanitizeSheetName(raw)
	if base == "" {
		base = "Sheet"
	}
	count := used[base]
	if count == 0 {
		used[base] = 1
		return base
	}
	for idx := count + 1; ; idx++ {
		suffix := fmt.Sprintf(" %d", idx)
		candidate := base
		if len([]rune(candidate))+len([]rune(suffix)) > 31 {
			candidate = string([]rune(candidate)[:31-len([]rune(suffix))])
		}
		candidate += suffix
		if used[candidate] == 0 {
			used[base] = idx
			used[candidate] = 1
			return candidate
		}
	}
}

func officeSanitizeSheetName(raw string) string {
	replacer := strings.NewReplacer("\\", " ", "/", " ", "?", " ", "*", " ", "[", " ", "]", " ", ":", " ")
	clean := strings.TrimSpace(replacer.Replace(raw))
	clean = strings.Join(strings.Fields(clean), " ")
	if clean == "" {
		return ""
	}
	runes := []rune(clean)
	if len(runes) > 31 {
		return string(runes[:31])
	}
	return clean
}

func officeInferXLSXColumnWidth(column officeColumnSpec, rows [][]interface{}, columnIndex int) float64 {
	if column.Width > 0 {
		return officeClampFloat(column.Width, 8, 48)
	}
	maxLen := officeMaxLineRunes(column.Header)
	sample := len(rows)
	if sample > 40 {
		sample = 40
	}
	for idx := 0; idx < sample; idx++ {
		if columnIndex >= len(rows[idx]) {
			continue
		}
		text := officeCellString(rows[idx][columnIndex])
		if lineLen := officeMaxLineRunes(text); lineLen > maxLen {
			maxLen = lineLen
		}
	}
	width := float64(maxLen + 2)
	switch strings.ToLower(strings.TrimSpace(column.Kind)) {
	case "number":
		return officeClampFloat(width, 10, 16)
	case "wrap":
		return officeClampFloat(width+4, 18, 36)
	default:
		if maxLen > 28 {
			return officeClampFloat(width+2, 14, 42)
		}
		return officeClampFloat(width, 10, 24)
	}
}

func officeMaxLineRunes(text string) int {
	lines := strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
	maxLen := 0
	for _, line := range lines {
		if l := runeCount(strings.TrimSpace(line)); l > maxLen {
			maxLen = l
		}
	}
	return maxLen
}

