func (w *officeStreamWriter) writeXMLText(text string) {
	if text == "" || w.err != nil {
		return
	}
	if officeXMLTextCanWriteRawASCII(text) {
		w.writeString(text)
		return
	}
	start := 0
	for i := 0; i < len(text) && w.err == nil; {
		r, width := utf8.DecodeRuneInString(text[i:])
		escape := ""
		switch r {
		case '"':
			escape = "&#34;"
		case '\'':
			escape = "&#39;"
		case '&':
			escape = "&amp;"
		case '<':
			escape = "&lt;"
		case '>':
			escape = "&gt;"
		case '\t':
			escape = "&#x9;"
		case '\n':
			escape = "&#xA;"
		case '\r':
			escape = "&#xD;"
		default:
			if officeXMLRuneAllowed(r) && !(r == utf8.RuneError && width == 1) {
				i += width
				continue
			}
			escape = "\uFFFD"
		}
		if start < i {
			w.writeString(text[start:i])
		}
		w.writeString(escape)
		i += width
		start = i
	}
	if start < len(text) {
		w.writeString(text[start:])
	}
}

