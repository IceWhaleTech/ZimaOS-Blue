func officeResolveXLSXCellValue(value interface{}, rawType, format string, forceString bool) (officeXLSXResolvedCellValue, bool) {
	cellType := strings.ToLower(strings.TrimSpace(rawType))
	switch cellType {
	case "bool", "boolean":
		text := strings.ToLower(strings.TrimSpace(officeCellString(value)))
		if text == "true" || text == "1" {
			return officeXLSXResolvedCellValue{CellType: "b", Text: "1"}, true
		}
		if text == "false" || text == "0" || text == "" {
			return officeXLSXResolvedCellValue{CellType: "b", Text: "0"}, true
		}
	case "text", "string", "inline_str", "inline":
		text := officeCellString(value)
		if text == "" {
			return officeXLSXResolvedCellValue{}, false
		}
		return officeXLSXResolvedCellValue{CellType: "inlineStr", Text: text, InlineString: true}, true
	case "number", "numeric":
		if number, ok := officeCellNumber(value); ok {
			return officeXLSXResolvedCellValue{Text: officeNumericXMLValue(number)}, true
		}
	}

	switch format {
	case "date":
		if serial, ok := officeExcelDateSerial(value, false); ok {
			return officeXLSXResolvedCellValue{Text: serial}, true
		}
	case "datetime":
		if serial, ok := officeExcelDateSerial(value, true); ok {
			return officeXLSXResolvedCellValue{Text: serial}, true
		}
	case "text":
		text := officeCellString(value)
		if text == "" {
			return officeXLSXResolvedCellValue{}, false
		}
		return officeXLSXResolvedCellValue{CellType: "inlineStr", Text: text, InlineString: true}, true
	}

	if !forceString {
		if number, ok := officeCellNumber(value); ok {
			return officeXLSXResolvedCellValue{Text: officeNumericXMLValue(number)}, true
		}
	}
	text := officeCellString(value)
	if text == "" {
		return officeXLSXResolvedCellValue{}, false
	}
	return officeXLSXResolvedCellValue{CellType: "inlineStr", Text: text, InlineString: true}, true
}

