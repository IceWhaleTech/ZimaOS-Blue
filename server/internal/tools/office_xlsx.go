func officeAppendXLSXCellRefBytes(dst []byte, colIndex, rowIndex int) []byte {
	colIndex++
	var colBuf [16]byte
	pos := len(colBuf)
	for colIndex > 0 {
		colIndex--
		pos--
		colBuf[pos] = byte('A' + colIndex%26)
		colIndex /= 26
	}
	dst = append(dst, colBuf[pos:]...)
	return strconv.AppendInt(dst, int64(rowIndex), 10)
}

func officeAppendXLSXCellStartBytes(dst []byte, rowIndex, colIndex, style int, cellType string) []byte {
	dst = append(dst, `<c r="`...)
	dst = officeAppendXLSXCellRefBytes(dst, colIndex, rowIndex)
	dst = append(dst, '"')
	if style > 0 {
		dst = append(dst, ` s="`...)
		dst = strconv.AppendInt(dst, int64(style), 10)
		dst = append(dst, '"')
	}
	if cellType != "" {
		dst = append(dst, ` t="`...)
		dst = append(dst, cellType...)
		dst = append(dst, '"')
	}
	return dst
}

