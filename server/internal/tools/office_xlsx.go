func officeEstimateXLSXWorksheetXMLSize(sheet officeXLSXSheetBuild) int {
	cellCount := 0
	mergeTextLen := 0
	for _, row := range sheet.Rows {
		cellCount += len(row.Cells)
	}
	for _, merge := range sheet.Merges {
		mergeTextLen += len(merge)
	}
	return 512 +
		len(sheet.Rows)*32 +
		cellCount*56 +
		len(sheet.ColWidths)*48 +
		len(sheet.ColStyles)*16 +
		len(sheet.Merges)*24 +
		mergeTextLen +
		len(sheet.AutoFilter)
}

