func officeResolveStreamCellValue(value interface{}, rawType, format string, forceString bool) (officeStreamResolvedCellValue, bool) {
	cellType := strings.ToLower(strings.TrimSpace(rawType))
	switch cellType {
	case "bool", "boolean":
		text := strings.ToLower(strings.TrimSpace(officeCellString(value)))
		if text == "true" || text == "1" {
			return officeStreamResolvedCellValue{cellType: "b", scalarText: "1", mode: officeStreamCellValueScalar}, true
		}
		if text == "false" || text == "0" || text == "" {
			return officeStreamResolvedCellValue{cellType: "b", scalarText: "0", mode: officeStreamCellValueScalar}, true
		}
	case "text", "string", "inline_str", "inline":
		text := officeCellString(value)
		if text == "" {
			return officeStreamResolvedCellValue{}, false
		}
		return officeStreamResolvedCellValue{cellType: "inlineStr", inlineText: text, mode: officeStreamCellValueInline}, true
	case "number", "numeric":
		if number, ok := officeCellNumber(value); ok {
			return officeStreamResolvedCellValue{number: number, mode: officeStreamCellValueNumber}, true
		}
	}

	switch format {
	case "date":
		if serial, ok := officeExcelDateSerial(value, false); ok {
			return officeStreamResolvedCellValue{scalarText: serial, mode: officeStreamCellValueScalar}, true
		}
	case "datetime":
		if serial, ok := officeExcelDateSerial(value, true); ok {
			return officeStreamResolvedCellValue{scalarText: serial, mode: officeStreamCellValueScalar}, true
		}
	case "text":
		text := officeCellString(value)
		if text == "" {
			return officeStreamResolvedCellValue{}, false
		}
		return officeStreamResolvedCellValue{cellType: "inlineStr", inlineText: text, mode: officeStreamCellValueInline}, true
	}

	if !forceString {
		if number, ok := officeCellNumber(value); ok {
			return officeStreamResolvedCellValue{number: number, mode: officeStreamCellValueNumber}, true
		}
	}
	text := officeCellString(value)
	if text == "" {
		return officeStreamResolvedCellValue{}, false
	}
	return officeStreamResolvedCellValue{cellType: "inlineStr", inlineText: text, mode: officeStreamCellValueInline}, true
}

