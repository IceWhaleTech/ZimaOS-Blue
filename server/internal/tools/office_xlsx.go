func officeAppendXLSXFreezePaneXML(sb *strings.Builder, ref string) {
	ref = strings.TrimSpace(ref)
	if ref == "" {
		return
	}
	col, row, ok := officeParseCellRef(ref)
	if !ok || row <= 1 && col <= 1 {
		return
	}
	pane := "bottomLeft"
	if col > 1 && row > 1 {
		pane = "bottomRight"
	} else if col > 1 {
		pane = "topRight"
	}

	sb.WriteString(`<pane`)
	if col > 1 {
		sb.WriteString(` xSplit="`)
		officeAppendInt(sb, col-1)
		sb.WriteString(`"`)
	}
	if row > 1 {
		sb.WriteString(` ySplit="`)
		officeAppendInt(sb, row-1)
		sb.WriteString(`"`)
	}
	sb.WriteString(` topLeftCell="`)
	officeAppendXMLText(sb, ref)
	sb.WriteString(`" activePane="`)
	sb.WriteString(pane)
	sb.WriteString(`" state="frozen"/>`)
	sb.WriteString(`<selection pane="`)
	sb.WriteString(pane)
	sb.WriteString(`" activeCell="`)
	officeAppendXMLText(sb, ref)
	sb.WriteString(`" sqref="`)
	officeAppendXMLText(sb, ref)
	sb.WriteString(`"/>`)
}

func officeParseCellRef(ref string) (int, int, bool) {
	ref = strings.TrimSpace(ref)
	if ref == "" {
		return 0, 0, false
	}
	col := 0
	row := 0
	seenLetter := false
	for _, r := range ref {
		switch {
		case r >= 'A' && r <= 'Z':
			col = col*26 + int(r-'A'+1)
			seenLetter = true
		case r >= 'a' && r <= 'z':
			col = col*26 + int(r-'a'+1)
			seenLetter = true
		case r >= '0' && r <= '9':
			if !seenLetter {
				return 0, 0, false
			}
			row = row*10 + int(r-'0')
		default:
			return 0, 0, false
		}
	}
	if col <= 0 || row <= 0 {
		return 0, 0, false
	}
	return col, row, true
}

