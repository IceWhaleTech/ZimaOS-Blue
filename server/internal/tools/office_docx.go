func parseMarkdownishOfficeDoc(content string) officeDocSpec {
	spec := officeDocSpec{}
	normalized := strings.ReplaceAll(content, "\r\n", "\n")
	blocks := strings.Split(normalized, "\n\n")
	currentSection := -1

	appendTopParagraph := func(text string) {
		text = strings.TrimSpace(text)
		if text == "" {
			return
		}
		lower := strings.ToLower(text)
		if strings.HasPrefix(lower, "summary:") || strings.HasPrefix(lower, "摘要：") || strings.HasPrefix(lower, "摘要:") {
			text = strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(strings.TrimPrefix(text, "Summary:"), "摘要:"), "摘要："))
			if text != "" {
				spec.Summary = text
			}
			return
		}
		if spec.Title != "" && spec.Subtitle == "" && spec.Summary == "" && len(spec.Paragraphs) == 0 && runeCount(text) <= 96 {
			spec.Subtitle = text
			return
		}
		if spec.Summary == "" {
			spec.Summary = text
			return
		}
		spec.Paragraphs = append(spec.Paragraphs, text)
	}

	appendSectionParagraph := func(text string) {
		text = strings.TrimSpace(text)
		if text == "" {
			return
		}
		if currentSection >= 0 && currentSection < len(spec.Sections) {
			spec.Sections[currentSection].Paragraphs = append(spec.Sections[currentSection].Paragraphs, text)
			return
		}
		appendTopParagraph(text)
	}

	startSection := func(heading string) {
		spec.Sections = append(spec.Sections, officeDocSection{Heading: strings.TrimSpace(heading)})
		currentSection = len(spec.Sections) - 1
	}

	for _, block := range blocks {
		lines := officeTrimmedLines(block)
		if len(lines) == 0 {
			continue
		}

		if heading, level, ok := officeMarkdownHeading(lines[0]); ok {
			if level == 1 && spec.Title == "" && currentSection < 0 && spec.Summary == "" && len(spec.Paragraphs) == 0 {
				spec.Title = heading
			} else {
				startSection(heading)
			}
			lines = lines[1:]
			if len(lines) == 0 {
				continue
			}
		}

		if officeAllBulletLines(lines) {
			bullets := officeMarkdownBullets(lines)
			if len(bullets) == 0 {
				continue
			}
			if currentSection >= 0 && currentSection < len(spec.Sections) {
				spec.Sections[currentSection].Bullets = append(spec.Sections[currentSection].Bullets, bullets...)
			} else {
				startSection("Highlights")
				spec.Sections[currentSection].Bullets = append(spec.Sections[currentSection].Bullets, bullets...)
			}
			continue
		}

		if table := officeParseMarkdownTable(lines); table != nil {
			if currentSection >= 0 && currentSection < len(spec.Sections) {
				spec.Sections[currentSection].Table = table
			} else {
				startSection("Table")
				spec.Sections[currentSection].Table = table
			}
			continue
		}

		paragraph := officeJoinTextFragments(lines)
		appendSectionParagraph(paragraph)
	}

	return spec
}

func officeTrimmedLines(block string) []string {
	rawLines := strings.Split(strings.ReplaceAll(block, "\r\n", "\n"), "\n")
	lines := make([]string, 0, len(rawLines))
	for _, line := range rawLines {
		if trimmed := strings.TrimSpace(line); trimmed != "" {
			lines = append(lines, trimmed)
		}
	}
	return lines
}

func officeMarkdownHeading(line string) (string, int, bool) {
	line = strings.TrimSpace(line)
	for level := 1; level <= 3; level++ {
		prefix := strings.Repeat("#", level) + " "
		if strings.HasPrefix(line, prefix) {
			return strings.TrimSpace(strings.TrimPrefix(line, prefix)), level, true
		}
	}
	return "", 0, false
}

func officeAllBulletLines(lines []string) bool {
	if len(lines) == 0 {
		return false
	}
	for _, line := range lines {
		if officeStripMarkdownBullet(line) == "" {
			return false
		}
	}
	return true
}

func officeMarkdownBullets(lines []string) []string {
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		if bullet := officeStripMarkdownBullet(line); bullet != "" {
			out = append(out, bullet)
		}
	}
	return out
}

func officeStripMarkdownBullet(line string) string {
	line = strings.TrimSpace(line)
	switch {
	case strings.HasPrefix(line, "- "):
		return strings.TrimSpace(strings.TrimPrefix(line, "- "))
	case strings.HasPrefix(line, "* "):
		return strings.TrimSpace(strings.TrimPrefix(line, "* "))
	case strings.HasPrefix(line, "• "):
		return strings.TrimSpace(strings.TrimPrefix(line, "• "))
	}
	for idx := 0; idx < len(line); idx++ {
		if line[idx] < '0' || line[idx] > '9' {
			if idx > 0 && idx+1 < len(line) && line[idx] == '.' && line[idx+1] == ' ' {
				return strings.TrimSpace(line[idx+2:])
			}
			break
		}
	}
	return ""
}

func officeParseMarkdownTable(lines []string) *officeTableSpec {
	if len(lines) < 2 {
		return nil
	}
	for _, line := range lines {
		if !strings.Contains(line, "|") {
			return nil
		}
	}
	headers := officeMarkdownTableCells(lines[0])
	if len(headers) == 0 || !officeMarkdownTableDivider(lines[1], len(headers)) {
		return nil
	}
	rows := make([][]string, 0, len(lines)-2)
	for _, line := range lines[2:] {
		cells := officeMarkdownTableCells(line)
		if len(cells) == 0 {
			continue
		}
		for len(cells) < len(headers) {
			cells = append(cells, "")
		}
		rows = append(rows, cells)
	}
	return &officeTableSpec{Headers: headers, Rows: rows}
}

func officeMarkdownTableCells(line string) []string {
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(line, "|")
	line = strings.TrimSuffix(line, "|")
	parts := strings.Split(line, "|")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		out = append(out, strings.TrimSpace(part))
	}
	return out
}

func officeMarkdownTableDivider(line string, columns int) bool {
	cells := officeMarkdownTableCells(line)
	if len(cells) != columns {
		return false
	}
	for _, cell := range cells {
		cell = strings.TrimSpace(strings.Trim(cell, ":"))
		if cell == "" {
			return false
		}
		for _, r := range cell {
			if r != '-' {
				return false
			}
		}
	}
	return true
}
