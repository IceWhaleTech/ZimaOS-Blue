func officeDOCXFontTableXML(theme officeTheme) string {
	fonts := []string{theme.BodyFont, theme.DisplayFont, theme.EastAsiaFont, theme.MonospaceFont}
	seen := make(map[string]struct{}, len(fonts))
	var sb strings.Builder
	sb.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`)
	sb.WriteString(`<w:fonts xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">`)
	for _, font := range fonts {
		font = strings.TrimSpace(font)
		if font == "" {
			continue
		}
		if _, ok := seen[font]; ok {
			continue
		}
		seen[font] = struct{}{}
		sb.WriteString(`<w:font w:name="`)
		sb.WriteString(officeXMLText(font))
		sb.WriteString(`"><w:family w:val="swiss"/></w:font>`)
	}
	sb.WriteString(`</w:fonts>`)
	return sb.String()
}

