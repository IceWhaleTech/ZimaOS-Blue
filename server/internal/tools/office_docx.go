func officeDOCXDocumentXML(spec officeDocSpec) string {
	var sb strings.Builder
	sb.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`)
	sb.WriteString(`<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">`)
	sb.WriteString(`<w:body>`)

	title := strings.TrimSpace(spec.Title)
	if title != "" {
		sb.WriteString(officeDOCXParagraphXML("BlueTitle", title))
	}
	if subtitle := strings.TrimSpace(spec.Subtitle); subtitle != "" {
		sb.WriteString(officeDOCXParagraphXML("BlueSubtitle", subtitle))
	}
	meta := "Generated " + time.Now().Format("2006-01-02") + "  •  Theme " + spec.Theme.Name
	if hint := strings.TrimSpace(spec.StyleHint); hint != "" {
		meta += "  •  " + hint
	}
	sb.WriteString(officeDOCXParagraphXML("BlueMeta", meta))

	for _, paragraph := range splitOfficeParagraphs(spec.Summary) {
		sb.WriteString(officeDOCXParagraphXML("BlueCallout", paragraph))
	}
	for _, paragraph := range spec.Paragraphs {
		paragraph = strings.TrimSpace(paragraph)
		if paragraph == "" {
			continue
		}
		sb.WriteString(officeDOCXParagraphXML("BlueBody", paragraph))
	}

	for _, section := range spec.Sections {
		if heading := strings.TrimSpace(section.Heading); heading != "" {
			sb.WriteString(officeDOCXParagraphXML("BlueHeading1", heading))
		}
		for _, paragraph := range section.Paragraphs {
			paragraph = strings.TrimSpace(paragraph)
			if paragraph == "" {
				continue
			}
			sb.WriteString(officeDOCXParagraphXML("BlueBody", paragraph))
		}
		for _, bullet := range section.Bullets {
			bullet = strings.TrimSpace(bullet)
			if bullet == "" {
				continue
			}
			sb.WriteString(officeDOCXParagraphXML("BlueBullet", "• "+bullet))
		}
		if section.Table != nil {
			sb.WriteString(officeDOCXTableXML(section.Table, spec.Theme))
		}
	}

	if len(spec.Notes) > 0 {
		sb.WriteString(officeDOCXParagraphXML("BlueHeading1", "Notes"))
		for _, note := range spec.Notes {
			note = strings.TrimSpace(note)
			if note == "" {
				continue
			}
			sb.WriteString(officeDOCXParagraphXML("BlueBullet", "• "+note))
		}
	}

	sb.WriteString(officeDOCXSectionPropsXML())
	sb.WriteString(`</w:body></w:document>`)
	return sb.String()
}

func officeDOCXParagraphXML(style, text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var sb strings.Builder
	sb.WriteString(`<w:p>`)
	if style != "" {
		sb.WriteString(`<w:pPr><w:pStyle w:val="`)
		sb.WriteString(style)
		sb.WriteString(`"/></w:pPr>`)
	}
	sb.WriteString(officeDOCXTextRunsXML(text, "", "", false))
	sb.WriteString(`</w:p>`)
	return sb.String()
}

func officeDOCXTextRunsXML(text, color, font string, bold bool) string {
	normalized := strings.ReplaceAll(text, "\r\n", "\n")
	parts := strings.Split(normalized, "\n")
	var sb strings.Builder
	runProps := officeDOCXRunPropsXML(color, font, bold)
	for idx, part := range parts {
		sb.WriteString(`<w:r>`)
		if runProps != "" {
			sb.WriteString(`<w:rPr>`)
			sb.WriteString(runProps)
			sb.WriteString(`</w:rPr>`)
		}
		sb.WriteString(`<w:t xml:space="preserve">`)
		sb.WriteString(officeXMLText(part))
		sb.WriteString(`</w:t></w:r>`)
		if idx < len(parts)-1 {
			sb.WriteString(`<w:r><w:br/></w:r>`)
		}
	}
	return sb.String()
}

func officeDOCXRunPropsXML(color, font string, bold bool) string {
	var sb strings.Builder
	if font = strings.TrimSpace(font); font != "" {
		sb.WriteString(`<w:rFonts w:ascii="`)
		sb.WriteString(officeXMLText(font))
		sb.WriteString(`" w:hAnsi="`)
		sb.WriteString(officeXMLText(font))
		sb.WriteString(`" w:eastAsia="`)
		sb.WriteString(officeXMLText(font))
		sb.WriteString(`"/>`)
	}
	if bold {
		sb.WriteString(`<w:b/>`)
	}
	if color = strings.TrimSpace(color); color != "" {
		sb.WriteString(`<w:color w:val="`)
		sb.WriteString(officeWordHex(color))
		sb.WriteString(`"/>`)
	}
	return sb.String()
}

func officeDOCXTableXML(table *officeTableSpec, theme officeTheme) string {
	if table == nil {
		return ""
	}
	columnCount := len(table.Headers)
	for _, row := range table.Rows {
		if len(row) > columnCount {
			columnCount = len(row)
		}
	}
	if columnCount == 0 {
		return ""
	}

	headers := append([]string(nil), table.Headers...)
	for len(headers) < columnCount {
		headers = append(headers, fmt.Sprintf("Column %d", len(headers)+1))
	}
	widths := officeDOCXColumnWidths(table, headers, table.Rows)

	var sb strings.Builder
	sb.WriteString(`<w:tbl>`)
	sb.WriteString(`<w:tblPr><w:tblW w:w="0" w:type="auto"/><w:tblBorders>`)
	for _, edge := range []string{"top", "left", "bottom", "right", "insideH", "insideV"} {
		sb.WriteString(`<w:` + edge + ` w:val="single" w:sz="6" w:space="0" w:color="` + officeWordHex(theme.Border) + `"/>`)
	}
	sb.WriteString(`</w:tblBorders><w:tblCellMar><w:top w:w="90" w:type="dxa"/><w:left w:w="120" w:type="dxa"/><w:bottom w:w="90" w:type="dxa"/><w:right w:w="120" w:type="dxa"/></w:tblCellMar></w:tblPr>`)
	sb.WriteString(`<w:tblGrid>`)
	for _, width := range widths {
		sb.WriteString(`<w:gridCol w:w="`)
		sb.WriteString(strconv.Itoa(width))
		sb.WriteString(`"/>`)
	}
	sb.WriteString(`</w:tblGrid>`)
	sb.WriteString(officeDOCXTableRowXML(table, headers, widths, theme.Primary, "FFFFFF", true))
	for idx, row := range table.Rows {
		fill := ""
		if idx%2 == 1 {
			fill = theme.SurfaceAlt
		}
		values := make([]string, columnCount)
		copy(values, row)
		sb.WriteString(officeDOCXTableRowXML(table, values, widths, fill, "", false))
	}
	sb.WriteString(`</w:tbl>`)
	return sb.String()
}

func officeDOCXTableRowXML(table *officeTableSpec, values []string, widths []int, fill, textColor string, bold bool) string {
	var sb strings.Builder
	sb.WriteString(`<w:tr>`)
	for idx, value := range values {
		width := 1800
		if idx < len(widths) {
			width = widths[idx]
		}
		sb.WriteString(officeDOCXTableCellXML(value, width, fill, textColor, bold, officeDOCXTableCellAlignment(table, idx)))
	}
	sb.WriteString(`</w:tr>`)
	return sb.String()
}

func officeDOCXTableCellXML(text string, width int, fill, textColor string, bold bool, alignment string) string {
	var sb strings.Builder
	sb.WriteString(`<w:tc><w:tcPr><w:tcW w:w="`)
	sb.WriteString(strconv.Itoa(width))
	sb.WriteString(`" w:type="dxa"/>`)
	if strings.TrimSpace(fill) != "" {
		sb.WriteString(`<w:shd w:val="clear" w:fill="`)
		sb.WriteString(officeWordHex(fill))
		sb.WriteString(`"/>`)
	}
	sb.WriteString(`<w:vAlign w:val="top"/></w:tcPr>`)
	sb.WriteString(`<w:p><w:pPr><w:spacing w:after="0" w:line="260" w:lineRule="auto"/>`)
	if wordAlignment := officeDOCXTableParagraphAlignment(alignment); wordAlignment != "" {
		sb.WriteString(`<w:jc w:val="`)
		sb.WriteString(wordAlignment)
		sb.WriteString(`"/>`)
	}
	sb.WriteString(`</w:pPr>`)
	sb.WriteString(officeDOCXTextRunsXML(strings.TrimSpace(text), textColor, "", bold))
	sb.WriteString(`</w:p></w:tc>`)
	return sb.String()
}

func officeDOCXTableCellAlignment(table *officeTableSpec, columnIndex int) string {
	if table == nil || columnIndex < 0 || columnIndex >= len(table.ColumnAlignments) {
		return ""
	}
	return table.ColumnAlignments[columnIndex]
}

func officeDOCXTableParagraphAlignment(alignment string) string {
	switch strings.ToLower(strings.TrimSpace(alignment)) {
	case "left":
		return "left"
	case "center":
		return "center"
	case "right":
		return "right"
	default:
		return ""
	}
}

func officeDOCXColumnWidths(table *officeTableSpec, headers []string, rows [][]string) []int {
	if widths := officeDOCXExplicitColumnWidths(table, len(headers)); len(widths) > 0 {
		return widths
	}
	weights := make([]int, len(headers))
	total := 0
	for idx, header := range headers {
		weight := officeMaxLineRunes(header) + 4
		for rowIdx := 0; rowIdx < len(rows) && rowIdx < 20; rowIdx++ {
			if idx >= len(rows[rowIdx]) {
				continue
			}
			if lineWeight := officeMaxLineRunes(rows[rowIdx][idx]) + 2; lineWeight > weight {
				weight = lineWeight
			}
		}
		if weight < 8 {
			weight = 8
		}
		weights[idx] = weight
		total += weight
	}
	if total == 0 {
		total = len(headers) * 8
	}
	widths := make([]int, len(headers))
	const tableWidth = 9000
	for idx, weight := range weights {
		width := tableWidth * weight / total
		if width < 1200 {
			width = 1200
		}
		widths[idx] = width
	}
	return widths
}

func officeDOCXExplicitColumnWidths(table *officeTableSpec, columnCount int) []int {
	if table == nil || columnCount <= 0 || len(table.ColumnWidths) == 0 {
		return nil
	}
	totalWeight := 0.0
	for idx := 0; idx < columnCount; idx++ {
		weight := 1.0
		if idx < len(table.ColumnWidths) && table.ColumnWidths[idx] > 0 {
			weight = table.ColumnWidths[idx]
		}
		totalWeight += weight
	}
	if totalWeight <= 0 {
		return nil
	}

	const tableWidth = 9000
	widths := make([]int, columnCount)
	remainingWidth := tableWidth
	remainingWeight := totalWeight
	for idx := range widths {
		weight := 1.0
		if idx < len(table.ColumnWidths) && table.ColumnWidths[idx] > 0 {
			weight = table.ColumnWidths[idx]
		}
		if idx == columnCount-1 || remainingWeight <= 0 {
			widths[idx] = remainingWidth
		} else {
			width := int(float64(tableWidth) * (weight / totalWeight))
			if width < 0 {
				width = 0
			}
			if width > remainingWidth {
				width = remainingWidth
			}
			widths[idx] = width
		}
		remainingWidth -= widths[idx]
		remainingWeight -= weight
	}
	return widths
}

