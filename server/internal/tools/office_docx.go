func parseMarkdownishOfficeDoc(content string) officeDocSpec {
	spec := officeDocSpec{}
	normalized := strings.ReplaceAll(content, "\r\n", "\n")
	blocks := strings.Split(normalized, "\n\n")
	currentSection := -1

	appendTopParagraph := func(text string) {
		text = strings.TrimSpace(text)
		if text == "" {
			return
		}
		lower := strings.ToLower(text)
		if strings.HasPrefix(lower, "summary:") || strings.HasPrefix(lower, "摘要：") || strings.HasPrefix(lower, "摘要:") {
			text = strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(strings.TrimPrefix(text, "Summary:"), "摘要:"), "摘要："))
			if text != "" {
				spec.Summary = text
			}
			return
		}
		if spec.Title != "" && spec.Subtitle == "" && spec.Summary == "" && len(spec.ParagraphBlocks) == 0 && len(spec.Paragraphs) == 0 && runeCount(text) <= 96 {
			spec.Subtitle = text
			return
		}
		if spec.Summary == "" {
			spec.Summary = text
			return
		}
		spec.ParagraphBlocks = append(spec.ParagraphBlocks, officeDocBlock{Kind: officeDocBlockParagraph, Text: text})
	}

	appendBlock := func(block officeDocBlock) {
		block.Text = strings.TrimSpace(block.Text)
		if block.Kind == officeDocBlockImage {
			block.Source = strings.TrimSpace(block.Source)
			if block.Source == "" {
				return
			}
		} else if block.Text == "" {
			return
		}
		if currentSection >= 0 && currentSection < len(spec.Sections) {
			spec.Sections[currentSection].ParagraphBlocks = append(spec.Sections[currentSection].ParagraphBlocks, block)
			return
		}
		if block.Kind == officeDocBlockParagraph {
			appendTopParagraph(block.Text)
			return
		}
		spec.ParagraphBlocks = append(spec.ParagraphBlocks, block)
	}

	startSection := func(heading string) {
		spec.Sections = append(spec.Sections, officeDocSection{Heading: strings.TrimSpace(heading)})
		currentSection = len(spec.Sections) - 1
	}

	for _, block := range blocks {
		block = strings.TrimSpace(strings.ReplaceAll(block, "\r\n", "\n"))
		if block == "" {
			continue
		}

		firstLine, rest := officeSplitFirstMarkdownLine(block)
		if heading, level, ok := officeMarkdownHeading(firstLine); ok {
			if level == 1 && spec.Title == "" && currentSection < 0 && spec.Summary == "" && len(spec.ParagraphBlocks) == 0 && len(spec.Paragraphs) == 0 {
				spec.Title = heading
			} else {
				startSection(heading)
			}
			block = strings.TrimSpace(rest)
			if block == "" {
				continue
			}
		}

		if alt, source, ok := officeMarkdownImageBlock(block); ok {
			appendBlock(officeDocBlock{Kind: officeDocBlockImage, Text: alt, Source: source})
			continue
		}
		if separator, ok := officeMarkdownThematicBreak(block); ok {
			appendBlock(officeDocBlock{Kind: officeDocBlockSeparator, Text: separator})
			continue
		}
		if code, ok := officeMarkdownFencedCodeBlock(block); ok {
			appendBlock(officeDocBlock{Kind: officeDocBlockCode, Text: code})
			continue
		}

		lines := officeTrimmedLines(block)
		if len(lines) == 0 {
			continue
		}
		if quote, ok := officeMarkdownBlockquote(lines); ok {
			appendBlock(officeDocBlock{Kind: officeDocBlockQuote, Text: quote})
			continue
		}
		if officeAllBulletLines(lines) {
			bullets := officeMarkdownBullets(lines)
			if len(bullets) == 0 {
				continue
			}
			if currentSection >= 0 && currentSection < len(spec.Sections) {
				spec.Sections[currentSection].Bullets = append(spec.Sections[currentSection].Bullets, bullets...)
			} else {
				startSection("Highlights")
				spec.Sections[currentSection].Bullets = append(spec.Sections[currentSection].Bullets, bullets...)
			}
			continue
		}

		if table := officeParseMarkdownTable(lines); table != nil {
			if currentSection >= 0 && currentSection < len(spec.Sections) {
				spec.Sections[currentSection].Table = table
			} else {
				startSection("Table")
				spec.Sections[currentSection].Table = table
			}
			continue
		}

		appendBlock(officeDocBlock{Kind: officeDocBlockParagraph, Text: officeJoinTextFragments(lines)})
	}

	return spec
}

func officeSplitFirstMarkdownLine(text string) (string, string) {
	text = strings.ReplaceAll(text, "\r\n", "\n")
	if idx := strings.IndexByte(text, '\n'); idx >= 0 {
		return strings.TrimSpace(text[:idx]), text[idx+1:]
	}
	return strings.TrimSpace(text), ""
}

func officeTrimmedLines(block string) []string {
	rawLines := strings.Split(strings.ReplaceAll(block, "\r\n", "\n"), "\n")
	lines := make([]string, 0, len(rawLines))
	for _, line := range rawLines {
		if trimmed := strings.TrimSpace(line); trimmed != "" {
			lines = append(lines, trimmed)
		}
	}
	return lines
}

func officeMarkdownHeading(line string) (string, int, bool) {
	line = strings.TrimSpace(line)
	for level := 1; level <= 3; level++ {
		prefix := strings.Repeat("#", level) + " "
		if strings.HasPrefix(line, prefix) {
			return strings.TrimSpace(strings.TrimPrefix(line, prefix)), level, true
		}
	}
	return "", 0, false
}

func officeAllBulletLines(lines []string) bool {
	if len(lines) == 0 {
		return false
	}
	for _, line := range lines {
		if _, ok := officeParseMarkdownListItem(line); !ok {
			return false
		}
	}
	return true
}

func officeMarkdownBullets(lines []string) []string {
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		if bullet, ok := officeParseMarkdownListItem(line); ok && bullet != "" {
			out = append(out, bullet)
		}
	}
	return out
}

func officeParseMarkdownListItem(line string) (string, bool) {
	line = strings.TrimSpace(line)
	switch {
	case strings.HasPrefix(line, "- [x] "), strings.HasPrefix(line, "- [X] "), strings.HasPrefix(line, "* [x] "), strings.HasPrefix(line, "* [X] "):
		return "☑ " + strings.TrimSpace(line[6:]), true
	case strings.HasPrefix(line, "- [ ] "), strings.HasPrefix(line, "* [ ] "):
		return "☐ " + strings.TrimSpace(line[6:]), true
	}
	if officeIsOrderedListItem(line) {
		return line, true
	}
	switch {
	case strings.HasPrefix(line, "- "):
		return strings.TrimSpace(strings.TrimPrefix(line, "- ")), true
	case strings.HasPrefix(line, "* "):
		return strings.TrimSpace(strings.TrimPrefix(line, "* ")), true
	case strings.HasPrefix(line, "• "):
		return strings.TrimSpace(strings.TrimPrefix(line, "• ")), true
	}
	return "", false
}

func officeIsOrderedListItem(line string) bool {
	line = strings.TrimSpace(line)
	if line == "" {
		return false
	}
	for idx := 0; idx < len(line); idx++ {
		if line[idx] >= '0' && line[idx] <= '9' {
			continue
		}
		if idx == 0 || idx+1 >= len(line) {
			return false
		}
		if (line[idx] == '.' || line[idx] == ')') && line[idx+1] == ' ' {
			return true
		}
		return false
	}
	return false
}

func officeOrderedListParts(text string) (int, string, bool) {
	text = strings.TrimSpace(text)
	if text == "" {
		return 0, "", false
	}
	prefixLen := 0
	for prefixLen < len(text) && text[prefixLen] >= '0' && text[prefixLen] <= '9' {
		prefixLen++
	}
	if prefixLen == 0 || prefixLen >= len(text) {
		return 0, "", false
	}
	if text[prefixLen] != '.' && text[prefixLen] != ')' {
		return 0, "", false
	}
	prefixLen++
	if prefixLen >= len(text) || text[prefixLen] != ' ' {
		return 0, "", false
	}
	start, err := strconv.Atoi(text[:prefixLen-1])
	if err != nil || start <= 0 {
		return 0, "", false
	}
	return start, strings.TrimSpace(text[prefixLen+1:]), true
}

func officeExplicitUnorderedListBody(text string) (string, bool) {
	trimmed := strings.TrimSpace(text)
	for _, prefix := range []string{"- ", "* ", "• "} {
		if strings.HasPrefix(trimmed, prefix) {
			return strings.TrimSpace(strings.TrimPrefix(trimmed, prefix)), true
		}
	}
	return "", false
}

func officeIsTaskListItem(text string) bool {
	text = strings.TrimSpace(text)
	return strings.HasPrefix(text, "☑ ") || strings.HasPrefix(text, "☐ ")
}

func officeRenderedListLine(text, defaultPrefix string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	if officeIsOrderedListItem(text) || officeIsTaskListItem(text) {
		return text
	}
	return defaultPrefix + text
}

func officeParseMarkdownTable(lines []string) *officeTableSpec {
	if len(lines) < 2 {
		return nil
	}
	for _, line := range lines {
		if !strings.Contains(line, "|") {
			return nil
		}
	}
	headers := officeMarkdownTableCells(lines[0])
	if len(headers) == 0 || !officeMarkdownTableDivider(lines[1], len(headers)) {
		return nil
	}
	rows := make([][]string, 0, len(lines)-2)
	for _, line := range lines[2:] {
		cells := officeMarkdownTableCells(line)
		if len(cells) == 0 {
			continue
		}
		for len(cells) < len(headers) {
			cells = append(cells, "")
		}
		rows = append(rows, cells)
	}
	return &officeTableSpec{Headers: headers, Rows: rows}
}

func officeMarkdownTableCells(line string) []string {
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(line, "|")
	line = strings.TrimSuffix(line, "|")
	parts := strings.Split(line, "|")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		out = append(out, strings.TrimSpace(part))
	}
	return out
}

func officeMarkdownTableDivider(line string, columns int) bool {
	cells := officeMarkdownTableCells(line)
	if len(cells) != columns {
		return false
	}
	for _, cell := range cells {
		cell = strings.TrimSpace(strings.Trim(cell, ":"))
		if cell == "" {
			return false
		}
		for _, r := range cell {
			if r != '-' {
				return false
			}
		}
	}
	return true
}
