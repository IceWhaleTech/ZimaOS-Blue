type officeDOCXHyperlink struct {
	RelID string
	URL   string
}

func buildOfficeDOCX(spec officeDocSpec) ([]byte, officeBuildInfo, error) {
	spec = cleanupOfficeDocSpec(spec)
	images, err := officeDOCXCollectImages(spec)
	if err != nil {
		return nil, officeBuildInfo{}, err
	}
	hyperlinks := officeDOCXCollectHyperlinks(spec)

	entries := []officeZipEntry{
		{Name: "[Content_Types].xml", Content: officeDOCXContentTypesXML(images)},
		{Name: "_rels/.rels", Content: officePackageRelsXML("word/document.xml")},
		{Name: "docProps/core.xml", Content: officeCorePropsXML(spec.Title, "Styled report generated by ZimaOS Blue")},
		{Name: "docProps/app.xml", Content: officeDOCXAppPropsXML(spec)},
		{Name: "word/document.xml", Content: officeDOCXDocumentXML(spec, hyperlinks, images)},
		{Name: "word/styles.xml", Content: officeDOCXStylesXML(spec.Theme)},
		{Name: "word/settings.xml", Content: officeDOCXSettingsXML()},
		{Name: "word/fontTable.xml", Content: officeDOCXFontTableXML(spec.Theme)},
		{Name: "word/numbering.xml", Content: officeDOCXNumberingXML()},
		{Name: "word/_rels/document.xml.rels", Content: officeDOCXDocumentRelsXML(hyperlinks, images)},
	}
	for _, image := range images {
		imageData := append([]byte(nil), image.Data...)
		entries = append(entries, officeZipEntry{
			Name:     image.EntryName,
			SizeHint: len(imageData),
			WriteTo: func(w io.Writer) error {
				_, err := w.Write(imageData)
				return err
			},
		})
	}

	data, err := officeBuildZip(entries)
	if err != nil {
		return nil, officeBuildInfo{}, err
	}

	paragraphCount := len(splitOfficeParagraphs(spec.Summary)) + len(spec.ParagraphBlocks) + len(spec.Paragraphs) + len(spec.Notes)
	for _, section := range spec.Sections {
		paragraphCount += len(section.ParagraphBlocks) + len(section.Paragraphs) + len(section.Bullets)
	}

	return data, officeBuildInfo{
		Format:         "docx",
		SectionCount:   len(spec.Sections),
		ParagraphCount: paragraphCount,
	}, nil
}

func officeDOCXCollectHyperlinks(spec officeDocSpec) []officeDOCXHyperlink {
	seen := map[string]string{}
	ordered := make([]officeDOCXHyperlink, 0, 4)
	nextID := 5

	collectText := func(text string) {
		for _, run := range parseOfficeInlineMarkdown(text) {
			url := strings.TrimSpace(run.LinkURL)
			if url == "" {
				continue
			}
			if _, ok := seen[url]; ok {
				continue
			}
			relID := "rId" + strconv.Itoa(nextID)
			nextID++
			seen[url] = relID
			ordered = append(ordered, officeDOCXHyperlink{RelID: relID, URL: url})
		}
	}

	collectText(spec.Title)
	collectText(spec.Subtitle)
	collectText(spec.Summary)
	for _, block := range officeDocBlocksOrParagraphs(spec.ParagraphBlocks, spec.Paragraphs) {
		if block.Kind == officeDocBlockCode || block.Kind == officeDocBlockSeparator || block.Kind == officeDocBlockImage {
			continue
		}
		collectText(block.Text)
	}
	for _, note := range spec.Notes {
		collectText(note)
	}
	for _, section := range spec.Sections {
		collectText(section.Heading)
		for _, block := range officeDocBlocksOrParagraphs(section.ParagraphBlocks, section.Paragraphs) {
			if block.Kind == officeDocBlockCode || block.Kind == officeDocBlockSeparator || block.Kind == officeDocBlockImage {
				continue
			}
			collectText(block.Text)
		}
		for _, bullet := range section.Bullets {
			collectText(bullet)
		}
		if section.Table == nil {
			continue
		}
		for _, header := range section.Table.Headers {
			collectText(header)
		}
		for _, row := range section.Table.Rows {
			for _, cell := range row {
				collectText(cell)
			}
		}
	}

	return ordered
}

func officeDOCXCollectImages(spec officeDocSpec) ([]officeEmbeddedImage, error) {
	ordered := make([]officeEmbeddedImage, 0, 4)
	seen := map[string]struct{}{}
	nextIndex := 1

	collectBlock := func(block officeDocBlock) error {
		if block.Kind != officeDocBlockImage {
			return nil
		}
		source := strings.TrimSpace(block.Source)
		if source == "" {
			return nil
		}
		if _, ok := seen[source]; ok {
			return nil
		}
		image, err := officeLoadEmbeddedImage(source)
		if err != nil {
			return err
		}
		image.Index = nextIndex
		image.RelID = "rId" + strconv.Itoa(100+nextIndex)
		image.EntryName = fmt.Sprintf("word/media/image%d.%s", nextIndex, strings.TrimPrefix(filepath.Ext(image.EntryName), "."))
		image.Target = fmt.Sprintf("media/image%d.%s", nextIndex, strings.TrimPrefix(filepath.Ext(image.EntryName), "."))
		nextIndex++
		seen[source] = struct{}{}
		ordered = append(ordered, image)
		return nil
	}

	for _, block := range officeDocBlocksOrParagraphs(spec.ParagraphBlocks, spec.Paragraphs) {
		if err := collectBlock(block); err != nil {
			return nil, err
		}
	}
	for _, section := range spec.Sections {
		for _, block := range officeDocBlocksOrParagraphs(section.ParagraphBlocks, section.Paragraphs) {
			if err := collectBlock(block); err != nil {
				return nil, err
			}
		}
	}
	return ordered, nil
}

func officeDOCXHyperlinkRelID(hyperlinks []officeDOCXHyperlink, url string) string {
	url = strings.TrimSpace(url)
	for _, link := range hyperlinks {
		if link.URL == url {
			return link.RelID
		}
	}
	return ""
}

