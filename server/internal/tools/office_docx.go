func officeDOCXDocumentXML(spec officeDocSpec, hyperlinks []officeDOCXHyperlink, images []officeEmbeddedImage) string {
	var sb strings.Builder
	sb.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`)
	sb.WriteString(`<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture" xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing">`)
	sb.WriteString(`<w:body>`)

	title := strings.TrimSpace(spec.Title)
	if title != "" {
		sb.WriteString(officeDOCXParagraphXML("BlueTitle", title, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
	}
	if subtitle := strings.TrimSpace(spec.Subtitle); subtitle != "" {
		sb.WriteString(officeDOCXParagraphXML("BlueSubtitle", subtitle, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
	}
	meta := "Generated " + time.Now().Format("2006-01-02") + "  •  Theme " + spec.Theme.Name
	if hint := strings.TrimSpace(spec.StyleHint); hint != "" {
		meta += "  •  " + hint
	}
	sb.WriteString(officeDOCXParagraphXML("BlueMeta", meta, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))

	for _, paragraph := range splitOfficeParagraphs(spec.Summary) {
		sb.WriteString(officeDOCXParagraphXML("BlueCallout", paragraph, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
	}
	for _, block := range officeDocBlocksOrParagraphs(spec.ParagraphBlocks, spec.Paragraphs) {
		sb.WriteString(officeDOCXBlockXML(block, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks, images))
	}

	for _, section := range spec.Sections {
		if heading := strings.TrimSpace(section.Heading); heading != "" {
			sb.WriteString(officeDOCXParagraphXML("BlueHeading1", heading, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
		}
		for _, block := range officeDocBlocksOrParagraphs(section.ParagraphBlocks, section.Paragraphs) {
			sb.WriteString(officeDOCXBlockXML(block, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks, images))
		}
		for _, bullet := range section.Bullets {
			bullet = strings.TrimSpace(bullet)
			if bullet == "" {
				continue
			}
			sb.WriteString(officeDOCXListParagraphXML(bullet, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
		}
		if section.Table != nil {
			sb.WriteString(officeDOCXTableXML(section.Table, spec.Theme, hyperlinks))
		}
	}

	if len(spec.Notes) > 0 {
		sb.WriteString(officeDOCXParagraphXML("BlueHeading1", "Notes", spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
		for _, note := range spec.Notes {
			note = strings.TrimSpace(note)
			if note == "" {
				continue
			}
			sb.WriteString(officeDOCXParagraphXML("BlueBullet", "• "+note, spec.Theme.MonospaceFont, spec.Theme.Accent, hyperlinks))
		}
	}

	sb.WriteString(officeDOCXSectionPropsXML())
	sb.WriteString(`</w:body></w:document>`)
	return sb.String()
}

func officeDOCXBlockXML(block officeDocBlock, monospaceFont, linkColor string, hyperlinks []officeDOCXHyperlink, images []officeEmbeddedImage) string {
	switch block.Kind {
	case officeDocBlockQuote:
		return officeDOCXParagraphXML("BlueCallout", block.Text, monospaceFont, linkColor, hyperlinks)
	case officeDocBlockCode:
		return officeDOCXPlainParagraphXML("BlueCodeBlock", block.Text, officeResolvedMonospaceFont(monospaceFont))
	case officeDocBlockSeparator:
		return officeDOCXSeparatorXML()
	case officeDocBlockImage:
		return officeDOCXImageXML(block, images)
	default:
		return officeDOCXParagraphXML("BlueBody", block.Text, monospaceFont, linkColor, hyperlinks)
	}
}

