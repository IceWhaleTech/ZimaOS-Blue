func officeDOCXTextRunsXML(text, color, font string, bold, italic bool, monospaceFont, linkColor string, hyperlinks []officeDOCXHyperlink) string {
	normalized := strings.ReplaceAll(text, "\r\n", "\n")
	parts := strings.Split(normalized, "\n")
	var sb strings.Builder
	for idx, part := range parts {
		runs := parseOfficeInlineMarkdown(part)
		if len(runs) == 0 {
			runs = []officeInlineRun{{Text: ""}}
		}
		for _, run := range runs {
			resolvedFont := strings.TrimSpace(font)
			if run.Code {
				resolvedFont = officeResolvedMonospaceFont(monospaceFont)
			}
			resolvedColor := color
			underline := false
			linkRelID := officeDOCXHyperlinkRelID(hyperlinks, run.LinkURL)
			if strings.TrimSpace(run.LinkURL) != "" {
				if strings.TrimSpace(resolvedColor) == "" {
					resolvedColor = strings.TrimSpace(linkColor)
					if resolvedColor == "" {
						resolvedColor = "2563EB"
					}
				}
				underline = true
			}
			if linkRelID != "" {
				sb.WriteString(`<w:hyperlink r:id="`)
				sb.WriteString(linkRelID)
				sb.WriteString(`" w:history="1">`)
			}
			sb.WriteString(`<w:r>`)
			if runProps := officeDOCXRunPropsXML(resolvedColor, resolvedFont, bold || run.Bold, italic || run.Italic, run.Strike, underline); runProps != "" {
				sb.WriteString(`<w:rPr>`)
				sb.WriteString(runProps)
				sb.WriteString(`</w:rPr>`)
			}
			sb.WriteString(`<w:t xml:space="preserve">`)
			sb.WriteString(officeXMLText(run.Text))
			sb.WriteString(`</w:t></w:r>`)
			if linkRelID != "" {
				sb.WriteString(`</w:hyperlink>`)
			}
		}
		if idx < len(parts)-1 {
			sb.WriteString(`<w:r><w:br/></w:r>`)
		}
	}
	return sb.String()
}

