func officeDOCXDocumentRelsXML(hyperlinks []officeDOCXHyperlink, images []officeEmbeddedImage) string {
	var sb strings.Builder
	sb.WriteString(`<?xml version="1.0" encoding="UTF-8"?>`)
	sb.WriteString(`<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">`)
	sb.WriteString(`<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>`)
	sb.WriteString(`<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/settings" Target="settings.xml"/>`)
	sb.WriteString(`<Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/fontTable" Target="fontTable.xml"/>`)
	sb.WriteString(`<Relationship Id="rId4" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/numbering" Target="numbering.xml"/>`)
	for _, link := range hyperlinks {
		sb.WriteString(`<Relationship Id="`)
		sb.WriteString(link.RelID)
		sb.WriteString(`" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink" Target="`)
		sb.WriteString(officeXMLText(link.URL))
		sb.WriteString(`" TargetMode="External"/>`)
	}
	for _, image := range images {
		sb.WriteString(`<Relationship Id="`)
		sb.WriteString(image.RelID)
		sb.WriteString(`" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="`)
		sb.WriteString(officeXMLText(image.Target))
		sb.WriteString(`"/>`)
	}
	sb.WriteString(`</Relationships>`)
	return sb.String()
}

