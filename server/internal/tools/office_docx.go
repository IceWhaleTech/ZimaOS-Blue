func buildOfficeDOCX(spec officeDocSpec) ([]byte, officeBuildInfo, error) {
	spec = cleanupOfficeDocSpec(spec)

	entries := []officeZipEntry{
		{Name: "[Content_Types].xml", Content: officeDOCXContentTypesXML()},
		{Name: "_rels/.rels", Content: officePackageRelsXML("word/document.xml")},
		{Name: "docProps/core.xml", Content: officeCorePropsXML(spec.Title, "Styled report generated by ZimaOS Blue")},
		{Name: "docProps/app.xml", Content: officeDOCXAppPropsXML(spec)},
		{Name: "word/document.xml", Content: officeDOCXDocumentXML(spec)},
		{Name: "word/styles.xml", Content: officeDOCXStylesXML(spec.Theme)},
		{Name: "word/settings.xml", Content: officeDOCXSettingsXML()},
		{Name: "word/fontTable.xml", Content: officeDOCXFontTableXML(spec.Theme)},
		{Name: "word/_rels/document.xml.rels", Content: officeDOCXDocumentRelsXML()},
	}

	data, err := officeBuildZip(entries)
	if err != nil {
		return nil, officeBuildInfo{}, err
	}

	paragraphCount := len(splitOfficeParagraphs(spec.Summary)) + len(spec.Paragraphs) + len(spec.Notes)
	for _, section := range spec.Sections {
		paragraphCount += len(section.Paragraphs) + len(section.Bullets)
	}

	return data, officeBuildInfo{
		Format:         "docx",
		SectionCount:   len(spec.Sections),
		ParagraphCount: paragraphCount,
	}, nil
}

