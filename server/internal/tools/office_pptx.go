func officePPTXChartSeriesStyleXML(series officeChartSeries) string {
	if series.Color == "" && series.LineWidth == 0 && series.Dash == "" {
		return ``
	}
	var style strings.Builder
	style.WriteString(`<c:spPr>`)
	if series.Color != "" {
		color := officeXMLText(series.Color)
		style.WriteString(`<a:solidFill><a:srgbClr val="` + color + `"/></a:solidFill>`)
	}
	if series.Color != "" || series.LineWidth > 0 || series.Dash != "" {
		lineWidth := officePPTXChartLineWidth(series.LineWidth)
		style.WriteString(fmt.Sprintf(`<a:ln w="%d">`, lineWidth))
		if series.Color != "" {
			color := officeXMLText(series.Color)
			style.WriteString(`<a:solidFill><a:srgbClr val="` + color + `"/></a:solidFill>`)
		}
		if series.Dash != "" {
			style.WriteString(`<a:prstDash val="` + officeXMLText(series.Dash) + `"/>`)
		}
		style.WriteString(`</a:ln>`)
	}
	style.WriteString(`</c:spPr>`)
	return style.String()
}

func officePPTXChartDataPointStylesXML(pointColors []string, pointExplosions []int, allowExplosion bool) string {
	pointCount := len(pointColors)
	if len(pointExplosions) > pointCount {
		pointCount = len(pointExplosions)
	}
	if pointCount == 0 {
		return ``
	}
	var xml strings.Builder
	for idx := 0; idx < pointCount; idx++ {
		color := ``
		if idx < len(pointColors) {
			color = pointColors[idx]
		}
		explosion := 0
		if allowExplosion && idx < len(pointExplosions) {
			explosion = pointExplosions[idx]
		}
		if color == "" && explosion <= 0 {
			continue
		}
		xml.WriteString(`<c:dPt><c:idx val="`)
		xml.WriteString(fmt.Sprintf("%d", idx))
		xml.WriteString(`"/>`)
		if explosion > 0 {
			xml.WriteString(`<c:explosion val="`)
			xml.WriteString(fmt.Sprintf("%d", explosion))
			xml.WriteString(`"/>`)
		}
		xml.WriteString(officePPTXChartPointStyleXML(color))
		xml.WriteString(`</c:dPt>`)
	}
	return xml.String()
}

