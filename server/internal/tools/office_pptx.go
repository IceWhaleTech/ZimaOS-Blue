func officePPTXTextRunsXMLWithOptions(text string, size int, bold, italic bool, monospaceFont string, parseInline bool, hyperlinks []officePPTXHyperlink) string {
	normalized := strings.ReplaceAll(text, "\r\n", "\n")
	parts := strings.Split(normalized, "\n")
	var sb strings.Builder
	for idx, part := range parts {
		runs := []officeInlineRun{{Text: part}}
		if parseInline {
			runs = parseOfficeInlineMarkdown(part)
			if len(runs) == 0 {
				runs = []officeInlineRun{{Text: part}}
			}
		}
		for _, run := range runs {
			resolvedFont := ""
			if !parseInline && strings.TrimSpace(monospaceFont) != "" {
				resolvedFont = officeResolvedMonospaceFont(monospaceFont)
			}
			if run.Code {
				resolvedFont = officeResolvedMonospaceFont(monospaceFont)
			}
			linkRelID := ""
			if parseInline {
				linkRelID = officePPTXHyperlinkRelID(hyperlinks, run.LinkURL)
			}
			sb.WriteString(officePPTXTextRunXML(run.Text, size, bold || run.Bold, italic || run.Italic, run.Strike, resolvedFont, linkRelID))
		}
		if idx < len(parts)-1 {
			sb.WriteString(`<a:br/>`)
		}
	}
	return sb.String()
}

func officePPTXParagraphXML(block officeDocBlock, theme officeTheme, hyperlinks []officePPTXHyperlink) string {
	var runs string
	font := theme.BodyFont
	color := theme.Slate
	size := 2200
	switch block.Kind {
	case officeDocBlockQuote:
		runs = officePPTXTextRunsXMLWithHyperlinks(block.Text, 2200, false, true, "", hyperlinks)
		color = theme.Secondary
	case officeDocBlockCode:
		runs = officePPTXTextRunsXMLWithOptions(block.Text, 1800, false, false, officeResolvedMonospaceFont(""), false, nil)
		color = theme.PrimaryDark
		size = 1800
	case officeDocBlockSeparator:
		return ""
	case officeDocBlockImage:
		return ""
	default:
		if startAt, text, ok := officeOrderedListParts(block.Text); ok {
			return officePPTXListParagraphXML(text, theme, hyperlinks, true, startAt)
		}
		if text, ok := officeExplicitUnorderedListBody(block.Text); ok {
			return officePPTXListParagraphXML(text, theme, hyperlinks, false, 0)
		}
		runs = officePPTXTextRunsXMLWithHyperlinks(block.Text, 2200, false, false, "", hyperlinks)
	}
	return officePPTXStyledParagraphXML(runs, font, color, size, "")
}

