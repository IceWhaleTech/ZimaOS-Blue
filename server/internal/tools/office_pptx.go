func officePPTXChartWorkbookSheetRef(sheetName string) string {
	sheetName = strings.TrimSpace(sheetName)
	if sheetName == "" {
		return "Sheet1"
	}
	if strings.ContainsAny(sheetName, " '") {
		return "'" + strings.ReplaceAll(sheetName, "'", "''") + "'"
	}
	return sheetName
}

