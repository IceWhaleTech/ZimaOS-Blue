func officePPTXComboChartPlotXML(chart officeChartSpec, primaryCatAxisID, primaryValAxisID, secondaryCatAxisID, secondaryValAxisID int, workbook *officePPTXChartWorkbookPackage) string {
	labelConfig := officePPTXChartLabelConfigFromChart(chart)
	barPrimary := make([]officeChartSeries, 0, len(chart.Series))
	barSecondary := make([]officeChartSeries, 0, len(chart.Series))
	linePrimary := make([]officeChartSeries, 0, len(chart.Series))
	lineSecondary := make([]officeChartSeries, 0, len(chart.Series))
	for idx, series := range chart.Series {
		normalized := series
		normalized.Type = officeNormalizeChartSeriesType("combo", series.Type, idx)
		normalized.Axis = officeNormalizeChartSeriesAxis("combo", normalized.Type, series.Axis)
		switch normalized.Type {
		case "line":
			if normalized.Axis == "secondary" {
				lineSecondary = append(lineSecondary, normalized)
			} else {
				linePrimary = append(linePrimary, normalized)
			}
		default:
			if normalized.Axis == "secondary" {
				barSecondary = append(barSecondary, normalized)
			} else {
				barPrimary = append(barPrimary, normalized)
			}
		}
	}

	var plot strings.Builder
	plot.WriteString(officePPTXBarChartGroupXML("bar", labelConfig, chart.Categories, barPrimary, chart.GapWidth, chart.Overlap, officePPTXChartVaryColors(chart, false), "col", "clustered", true, chart.CategoryAxisType, chart.CategoryAxisFormat, primaryCatAxisID, primaryValAxisID, workbook))
	plot.WriteString(officePPTXLineChartGroupXML("line", labelConfig, chart.Categories, linePrimary, chart.Smooth, officePPTXChartVaryColors(chart, false), chart.CategoryAxisType, chart.CategoryAxisFormat, primaryCatAxisID, primaryValAxisID, workbook))
	plot.WriteString(officePPTXBarChartGroupXML("bar", labelConfig, chart.Categories, barSecondary, chart.GapWidth, chart.Overlap, officePPTXChartVaryColors(chart, false), "col", "clustered", true, chart.CategoryAxisType, chart.SecondaryCategoryAxisFormat, secondaryCatAxisID, secondaryValAxisID, workbook))
	plot.WriteString(officePPTXLineChartGroupXML("line", labelConfig, chart.Categories, lineSecondary, chart.Smooth, officePPTXChartVaryColors(chart, false), chart.CategoryAxisType, chart.SecondaryCategoryAxisFormat, secondaryCatAxisID, secondaryValAxisID, workbook))
	return plot.String()
}

