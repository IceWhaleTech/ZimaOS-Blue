func officePPTXChartDataLabelOptions(chartType string, labelConfig officePPTXChartLabelConfig, seriesList []officeChartSeries) officePPTXDataLabelOptions {
	show := officePPTXChartShowsDataLabels(labelConfig.Labels, seriesList)
	if !show {
		return officePPTXDataLabelOptions{}
	}
	options := officePPTXDataLabelOptions{
		Show:           true,
		Position:       labelConfig.Position,
		Format:         labelConfig.Format,
		ShowValue:      true,
		ShowCategory:   chartType == "pie" || chartType == "donut",
		ShowSeriesName: false,
		ShowPercent:    false,
		ShowLegendKey:  false,
		ShowBubbleSize: false,
	}
	if labelConfig.ShowValue != "" {
		options.ShowValue = labelConfig.ShowValue == "show"
	}
	if labelConfig.ShowCategory != "" {
		options.ShowCategory = labelConfig.ShowCategory == "show"
	}
	if labelConfig.ShowSeriesName != "" {
		options.ShowSeriesName = labelConfig.ShowSeriesName == "show"
	}
	if labelConfig.ShowPercent != "" {
		options.ShowPercent = labelConfig.ShowPercent == "show"
	}
	if labelConfig.ShowLegendKey != "" {
		options.ShowLegendKey = labelConfig.ShowLegendKey == "show"
	}
	if labelConfig.ShowBubbleSize != "" {
		options.ShowBubbleSize = labelConfig.ShowBubbleSize == "show"
	}
	for _, series := range seriesList {
		if labelConfig.Labels != "show" && series.Labels != "show" {
			continue
		}
		if series.LabelPosition != "" {
			options.Position = series.LabelPosition
		}
		if series.LabelFormat != "" {
			options.Format = series.LabelFormat
		}
		if series.ShowValue != "" {
			options.ShowValue = series.ShowValue == "show"
		}
		if series.ShowCategory != "" {
			options.ShowCategory = series.ShowCategory == "show"
		}
		if series.ShowSeriesName != "" {
			options.ShowSeriesName = series.ShowSeriesName == "show"
		}
		if series.ShowPercent != "" {
			options.ShowPercent = series.ShowPercent == "show"
		}
		if series.ShowLegendKey != "" {
			options.ShowLegendKey = series.ShowLegendKey == "show"
		}
		if series.ShowBubbleSize != "" {
			options.ShowBubbleSize = series.ShowBubbleSize == "show"
		}
	}
	return options
}

