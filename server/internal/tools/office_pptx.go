func officePPTXChartApplyTheme(chart officeChartSpec, theme officeTheme) officeChartSpec {
	palette := officePPTXChartThemePalette(theme)
	if len(palette) == 0 {
		return chart
	}
	if chart.Type == "pie" || chart.Type == "donut" {
		if len(chart.Series) > 0 {
			series := chart.Series[0]
			series.PointColors = officePPTXChartPointPalette(series.PointColors, palette, len(chart.Categories))
			if series.Color == "" && len(series.PointColors) > 0 {
				series.Color = series.PointColors[0]
			}
			chart.Series[0] = series
		}
		return chart
	}
	for idx := range chart.Series {
		if strings.TrimSpace(chart.Series[idx].Color) == "" {
			chart.Series[idx].Color = palette[idx%len(palette)]
		}
	}
	return chart
}

func officePPTXChartThemePalette(theme officeTheme) []string {
	colors := []string{
		officeWordHex(theme.Primary),
		officeWordHex(theme.Accent),
		officeWordHex(theme.Secondary),
		officeWordHex(theme.Success),
		officeWordHex(theme.Warning),
		officeWordHex(theme.Danger),
		officeWordHex(theme.PrimaryDark),
		officeWordHex(theme.Slate),
	}
	palette := make([]string, 0, len(colors))
	seen := map[string]struct{}{}
	for _, color := range colors {
		if color == "" || color == "000000" {
			continue
		}
		if _, ok := seen[color]; ok {
			continue
		}
		seen[color] = struct{}{}
		palette = append(palette, color)
	}
	return palette
}

func officePPTXChartPointPalette(existing, palette []string, pointCount int) []string {
	if pointCount <= 0 || len(palette) == 0 {
		return existing
	}
	if len(existing) >= pointCount {
		return existing
	}
	out := make([]string, pointCount)
	copy(out, existing)
	for idx := range out {
		if strings.TrimSpace(out[idx]) != "" {
			out[idx] = officeWordHex(out[idx])
			continue
		}
		out[idx] = palette[idx%len(palette)]
	}
	return out
}

