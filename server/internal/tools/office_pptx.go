func officePPTXSlideRelsXMLForSlide(slide officePPTXSlide, chartIndex int) string {
	rels := `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` +
		`<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">` +
		`<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideLayout" Target="../slideLayouts/slideLayout1.xml"/>`
	if chartIndex > 0 {
		rels += fmt.Sprintf(`<Relationship Id="%s" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/chart" Target="../charts/chart%d.xml"/>`, officeXMLText(firstNonEmptyOfficeString(slide.chartRelID, "rId2")), chartIndex)
	}
	for _, image := range slide.images {
		rels += `<Relationship Id="` + officeXMLText(image.RelID) + `" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="` + officeXMLText(image.Target) + `"/>`
	}
	for _, link := range slide.hyperlinks {
		rels += `<Relationship Id="` + officeXMLText(link.RelID) + `" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink" Target="` + officeXMLText(link.URL) + `" TargetMode="External"/>`
	}
	rels += `</Relationships>`
	return rels
}
