func officePPTXChartCircularSeriesXML(chart officeChartSpec) string {
	if len(chart.Series) == 0 {
		return ``
	}
	series := chart.Series[0]
	var seriesXML strings.Builder
	seriesXML.WriteString(`<c:ser>`)
	seriesXML.WriteString(`<c:idx val="0"/><c:order val="0"/>`)
	seriesXML.WriteString(`<c:tx><c:v>`)
	seriesXML.WriteString(officeXMLText(series.Name))
	seriesXML.WriteString(`</c:v></c:tx>`)
	seriesXML.WriteString(officePPTXChartSeriesStyleXML(series))
	seriesXML.WriteString(officePPTXChartDataPointStylesXML(series.PointColors, series.PointExplosions, true))
	seriesXML.WriteString(`<c:cat><c:strLit><c:ptCount val="`)
	seriesXML.WriteString(fmt.Sprintf("%d", len(chart.Categories)))
	seriesXML.WriteString(`"/>`)
	for catIndex, category := range chart.Categories {
		seriesXML.WriteString(fmt.Sprintf(`<c:pt idx="%d"><c:v>%s</c:v></c:pt>`, catIndex, officeXMLText(category)))
	}
	seriesXML.WriteString(`</c:strLit></c:cat>`)
	seriesXML.WriteString(`<c:val><c:numLit><c:formatCode>General</c:formatCode><c:ptCount val="`)
	seriesXML.WriteString(fmt.Sprintf("%d", len(series.Values)))
	seriesXML.WriteString(`"/>`)
	for valueIndex, value := range series.Values {
		seriesXML.WriteString(fmt.Sprintf(`<c:pt idx="%d"><c:v>%s</c:v></c:pt>`, valueIndex, officePPTXChartNumber(value)))
	}
	seriesXML.WriteString(`</c:numLit></c:val>`)
	seriesXML.WriteString(`</c:ser>`)
	return seriesXML.String()
}

