		return officePPTXLineChartGroupXML("line", labelConfig, chart.Categories, chart.Series, chart.Smooth, officePPTXChartVaryColors(chart, false), chart.CategoryAxisType, chart.CategoryAxisFormat, primaryCatAxisID, primaryValAxisID, workbook)
