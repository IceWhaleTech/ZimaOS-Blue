func buildOfficePPTX(spec officeDocSpec) ([]byte, officeBuildInfo, error) {
	slides := officeBuildPresentationSlides(spec)
	if len(slides) == 0 {
		return nil, officeBuildInfo{}, fmt.Errorf("pptx output requires at least one slide")
	}

	chartCount := 0
	embeddedWorkbookCount := 0
	for idx := range slides {
		if slides[idx].Chart != nil {
			chartCount++
			slides[idx].chartRelID = "rId2"
		}
	}

	entries := []officeZipEntry{
		{Name: "[Content_Types].xml", Content: officePPTXContentTypesXML(len(slides), chartCount, embeddedWorkbookCount)},
		{Name: "_rels/.rels", Content: officePackageRelsXML("ppt/presentation.xml")},
		{Name: "docProps/core.xml", Content: officeCorePropsXML(spec.Title, "Presentation generated by ZimaOS Blue")},
		{Name: "docProps/app.xml", Content: officePPTXAppPropsXML(slides)},
		{Name: "ppt/presentation.xml", Content: officePPTXPresentationXML(len(slides))},
		{Name: "ppt/_rels/presentation.xml.rels", Content: officePPTXPresentationRelsXML(len(slides))},
		{Name: "ppt/slideMasters/slideMaster1.xml", Content: officePPTXSlideMasterXML()},
		{Name: "ppt/slideMasters/_rels/slideMaster1.xml.rels", Content: officePPTXSlideMasterRelsXML()},
		{Name: "ppt/slideLayouts/slideLayout1.xml", Content: officePPTXSlideLayoutXML()},
		{Name: "ppt/slideLayouts/_rels/slideLayout1.xml.rels", Content: officePPTXSlideLayoutRelsXML()},
		{Name: "ppt/theme/theme1.xml", Content: officePPTXThemeXML()},
	}
	nextChartIndex := 1
	for idx, slide := range slides {
		chartIndex := 0
		if slide.Chart != nil {
			chartIndex = nextChartIndex
			chartPackage, err := officeBuildPPTXChartPackage(*slide.Chart, chartIndex)
			if err != nil {
				return nil, officeBuildInfo{}, err
			}
			entries = append(entries, officeZipEntry{
				Name:    fmt.Sprintf("ppt/charts/chart%d.xml", chartIndex),
				Content: chartPackage.ChartXML,
			})
			if chartPackage.ChartRelsXML != "" {
				entries = append(entries, officeZipEntry{
					Name:    fmt.Sprintf("ppt/charts/_rels/chart%d.xml.rels", chartIndex),
					Content: chartPackage.ChartRelsXML,
				})
			}
			if chartPackage.Workbook != nil {
				embeddedWorkbookCount++
				workbookData := append([]byte(nil), chartPackage.Workbook.Data...)
				entries = append(entries, officeZipEntry{
					Name:     chartPackage.Workbook.EntryName,
					SizeHint: len(workbookData),
					WriteTo: func(w io.Writer) error {
						_, err := w.Write(workbookData)
						return err
					},
				})
			}
			nextChartIndex++
		}
		entries = append(entries,
			officeZipEntry{Name: fmt.Sprintf("ppt/slides/slide%d.xml", idx+1), Content: officePPTXSlideXML(slide)},
			officeZipEntry{Name: fmt.Sprintf("ppt/slides/_rels/slide%d.xml.rels", idx+1), Content: officePPTXSlideRelsXML(chartIndex)},
		)
	}
	entries[0].Content = officePPTXContentTypesXML(len(slides), chartCount, embeddedWorkbookCount)

	data, err := officeBuildZip(entries)
	if err != nil {
		return nil, officeBuildInfo{}, err
	}

	paragraphCount := 0
	for _, slide := range slides {
		paragraphCount += slide.paragraphCount()
	}
	return data, officeBuildInfo{
		Format:         "pptx",
		SectionCount:   len(slides),
		ParagraphCount: paragraphCount,
	}, nil
}

func officeBuildPresentationSlides(spec officeDocSpec) []officePPTXSlide {
	slides := make([]officePPTXSlide, 0, len(spec.Sections)+4)

	title := strings.TrimSpace(spec.Title)
	subtitle := strings.TrimSpace(spec.Subtitle)
	sectionTitles := officePPTXSectionTitles(spec.Sections)
	if title != "" || subtitle != "" {
		lines := []string(nil)
		if subtitle != "" {
			lines = append(lines, subtitle)
		}
		slides = append(slides, officePPTXSlide{
			Title: firstNonEmptyOfficeString(title, "Presentation"),
			Lines: lines,
		})
	}

	if len(sectionTitles) > 0 {
		tocLines := make([]string, 0, len(sectionTitles))
		for idx, sectionTitle := range sectionTitles {
			tocLines = append(tocLines, fmt.Sprintf("%d. %s", idx+1, sectionTitle))
		}
		slides = append(slides, officePPTXSlide{Title: "Table of Contents", Lines: tocLines})
	}
	if len(spec.Paragraphs) > 0 {
		slides = append(slides, officePPTXSlide{Title: "Content", Lines: officePPTXNormalizeLines(spec.Paragraphs...)})
	}

	for idx, section := range spec.Sections {
		lines := make([]string, 0, len(section.Paragraphs)+len(section.Bullets)+4)
		lines = append(lines, officePPTXNormalizeLines(section.Paragraphs...)...)
		for _, bullet := range officePPTXNormalizeLines(section.Bullets...) {
			lines = append(lines, "- "+bullet)
		}
		if len(lines) == 0 && officePPTXTableRowCount(section.Table) == 0 && section.Chart == nil {
			continue
		}
		title := strings.TrimSpace(section.Heading)
		if title == "" && section.Chart != nil {
			title = strings.TrimSpace(section.Chart.Title)
		}
		if title == "" {
			title = fmt.Sprintf("Slide %d", idx+1)
		}
		slides = append(slides, officePPTXSlide{Title: title, Lines: lines, Table: section.Table, Chart: section.Chart})
	}

	if summaryLines := officePPTXSummaryLines(spec); len(summaryLines) > 0 {
		slides = append(slides, officePPTXSlide{Title: "Summary", Lines: summaryLines})
	}

	if len(slides) == 0 {
		slides = append(slides, officePPTXSlide{
			Title: firstNonEmptyOfficeString(title, "Presentation"),
			Lines: officePPTXNormalizeLines(subtitle),
		})
	}
	return slides
}

func officePPTXSectionTitles(sections []officeDocSection) []string {
	titles := make([]string, 0, len(sections))
	for idx, section := range sections {
		title := strings.TrimSpace(section.Heading)
		if title == "" {
			title = fmt.Sprintf("Section %d", idx+1)
		}
		titles = append(titles, title)
	}
	return titles
}

func officePPTXSummaryLines(spec officeDocSpec) []string {
	lines := officePPTXNormalizeLines(spec.Summary)
	for _, note := range officePPTXNormalizeLines(spec.Notes...) {
		lines = append(lines, "- "+note)
	}
	return lines
}

func officePPTXNormalizeLines(values ...string) []string {
	lines := make([]string, 0, len(values))
	for _, value := range values {
		for _, line := range strings.Split(value, "\n") {
			line = strings.TrimSpace(line)
			if line == "" {
				continue
			}
			lines = append(lines, line)
		}
	}
	return lines
}

func officePPTXTableLines(table *officeTableSpec) []string {
	if table == nil {
		return nil
	}
	lines := make([]string, 0, len(table.Rows)+1)
	if len(table.Headers) > 0 {
		lines = append(lines, strings.Join(table.Headers, " | "))
	}
	for _, row := range table.Rows {
		cells := make([]string, 0, len(row))
		for _, cell := range row {
			cells = append(cells, anyToStringForLLM(cell))
		}
		lines = append(lines, strings.Join(cells, " | "))
	}
	return officePPTXNormalizeLines(lines...)
}

func (slide officePPTXSlide) paragraphCount() int {
	count := len(slide.Lines)
	count += officePPTXTableRowCount(slide.Table)
	return count
}

func officePPTXTableRowCount(table *officeTableSpec) int {
	if table == nil {
		return 0
	}
	count := len(table.Rows)
	if len(table.Headers) > 0 {
		count++
	}
	return count
}

func officeBuildPPTXChartPackage(chart officeChartSpec, chartIndex int) (officePPTXChartPackage, error) {
	chart = officeNormalizePPTXChart(chart)
	var workbook *officePPTXChartWorkbookPackage
	var err error
	if officePPTXChartShouldEmbedWorkbook(chart) {
		workbook, err = officePPTXChartWorkbookPackageForChart(chart, chartIndex)
		if err != nil {
			return officePPTXChartPackage{}, err
		}
	}
	return officePPTXChartPackage{
		ChartXML:     officePPTXChartXMLWithWorkbook(chart, workbook),
		ChartRelsXML: officePPTXChartRelsXML(workbook),
		Workbook:     workbook,
	}, nil
}

func officePPTXChartShouldEmbedWorkbook(chart officeChartSpec) bool {
	if !officePPTXChartUsesDateAxis(chart.CategoryAxisType) {
		return false
	}
	withTime := officePPTXChartDateAxisIncludesTime(chart.CategoryAxisType)
	for _, category := range chart.Categories {
		if _, ok := officeExcelDateSerial(category, withTime); !ok {
			return false
		}
	}
	return len(chart.Categories) > 0 && len(chart.Series) > 0
}

func officePPTXChartWorkbookPackageForChart(chart officeChartSpec, chartIndex int) (*officePPTXChartWorkbookPackage, error) {
	categoryFormat := officePPTXChartWorkbookCategoryKind(chart.CategoryAxisType)
	rows := make([][]interface{}, 0, len(chart.Categories))
	for rowIndex, category := range chart.Categories {
		row := make([]interface{}, 0, len(chart.Series)+1)
		categoryCell := interface{}(category)
		switch categoryFormat {
		case "date", "datetime":
			categoryCell = map[string]interface{}{
				"value":  category,
				"format": categoryFormat,
			}
		}
		row = append(row, categoryCell)
		for _, series := range chart.Series {
			value := 0.0
			if rowIndex < len(series.Values) {
				value = series.Values[rowIndex]
			}
			row = append(row, value)
		}
		rows = append(rows, row)
	}

	columns := make([]officeColumnSpec, 0, len(chart.Series)+1)
	columns = append(columns, officeColumnSpec{
		Header: firstNonEmptyOfficeString(strings.TrimSpace(chart.CategoryAxisTitle), "Category"),
		Key:    "category",
		Kind:   categoryFormat,
	})
	for idx, series := range chart.Series {
		columns = append(columns, officeColumnSpec{
			Header: firstNonEmptyOfficeString(strings.TrimSpace(series.Name), fmt.Sprintf("Series %d", idx+1)),
			Key:    fmt.Sprintf("series_%d", idx+1),
			Kind:   "decimal",
		})
	}

	workbookData, _, err := buildOfficeXLSX(officeWorkbookSpec{
		Theme: resolveOfficeTheme("analysis", ""),
		Sheets: []officeSheetSpec{
			{
				Name:    "Data",
				Columns: columns,
				Rows:    rows,
			},
		},
	})
	if err != nil {
		return nil, err
	}

	workbookName := fmt.Sprintf("Microsoft_Excel_Worksheet%d.xlsx", chartIndex)
	return &officePPTXChartWorkbookPackage{
		SheetName:          "Data",
		RelationshipID:     "rId1",
		RelationshipTarget: "../embeddings/" + workbookName,
		EntryName:          "ppt/embeddings/" + workbookName,
		Data:               workbookData,
	}, nil
}

func officePPTXChartWorkbookCategoryKind(categoryAxisType string) string {
	if officePPTXChartDateAxisIncludesTime(categoryAxisType) {
		return "datetime"
	}
	if officePPTXChartUsesDateAxis(categoryAxisType) {
		return "date"
	}
	return "text"
}

func officePPTXContentTypesXML(slideCount, chartCount, embeddedWorkbookCount int) string {
	var overrides strings.Builder
	for idx := 1; idx <= slideCount; idx++ {
		overrides.WriteString(fmt.Sprintf(`<Override PartName="/ppt/slides/slide%d.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>`, idx))
	}
	for idx := 1; idx <= chartCount; idx++ {
		overrides.WriteString(fmt.Sprintf(`<Override PartName="/ppt/charts/chart%d.xml" ContentType="application/vnd.openxmlformats-officedocument.drawingml.chart+xml"/>`, idx))
	}
	return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` +
		`<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
		`<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>` +
		`<Default Extension="xml" ContentType="application/xml"/>` +
		func() string {
			if embeddedWorkbookCount > 0 {
				return `<Default Extension="xlsx" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"/>`
			}
			return ``
		}() +
		`<Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>` +
		`<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>` +
		`<Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>` +
		`<Override PartName="/ppt/slideMasters/slideMaster1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideMaster+xml"/>` +
		`<Override PartName="/ppt/slideLayouts/slideLayout1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideLayout+xml"/>` +
		`<Override PartName="/ppt/theme/theme1.xml" ContentType="application/vnd.openxmlformats-officedocument.theme+xml"/>` +
		overrides.String() +
		`</Types>`
}

