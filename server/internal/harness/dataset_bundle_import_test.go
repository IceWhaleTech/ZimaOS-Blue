func TestController_ImportCommittedPinchBenchBundleRunsEvalAndProducesScorecards(t *testing.T) {
	controller := newTestController(t)
	var observedSeededWorkspace bool
	controller.RegisterDriver(&autoCompleteGroupDriver{
		kind:   RunKindAgentTask,
		status: RunStatusCompleted,
		result: "bundle task completed",
		delay:  5 * time.Millisecond,
		onStart: func(run *Run, _ RunEnv) error {
			if metadataString(run.Metadata, "dataset_case_id") == "task_15_daily_summary" {
				blob, err := os.ReadFile(filepath.Join(run.WorkspaceRoot, "research", "market_analysis.txt"))
				if err != nil {
					return err
				}
				observedSeededWorkspace = len(blob) > 0
			}
			expected, _ := run.Metadata["group_expected"].(map[string]interface{})
			for _, artifact := range decodeHarnessExpectedArtifacts(expected["expected_artifacts"]) {
				target := filepath.Join(run.WorkspaceRoot, artifact.Path)
				if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
					return err
				}
				if err := os.WriteFile(target, []byte("generated by test driver"), 0o644); err != nil {
					return err
				}
			}
			return nil
		},
	})

	workdir, err := os.Getwd()
	if err != nil {
		t.Fatalf("Getwd: %v", err)
	}
	bundleDir := filepath.Join(workdir, "..", "..", "..", "harness", "datasets", "pinchbench")

	req, err := loadImportDatasetBundleRequestFromDir(bundleDir, "")
	if err != nil {
		t.Fatalf("loadImportDatasetBundleRequestFromDir: %v", err)
	}
	if len(req.EvalSpecs) != 1 {
		t.Fatalf("eval specs len = %d, want 1", len(req.EvalSpecs))
	}
	req.EvalSpecs[0].SchedulerConfig.MaxConcurrency = 8
	req.EvalSpecs[0].SchedulerConfig.MaxAttempts = 1
	req.EvalSpecs[0].SchedulerConfig.RetryBackoff = 5 * time.Millisecond
	result, err := controller.ImportDatasetBundle(context.Background(), *req)
	if err != nil {
		t.Fatalf("ImportDatasetBundle failed: %v", err)
	}
	if result == nil || len(result.EvalSpecs) != 1 {
		t.Fatalf("result = %#v, want one eval spec", result)
	}

	evalRun, err := controller.SubmitEvalRun(context.Background(), EvalRunSpec{
		EvalSpecID:  result.EvalSpecs[0].ID,
		OwnerUserID: "bundle-owner",
		Title:       "pinchbench bundle eval",
	})
	if err != nil {
		t.Fatalf("SubmitEvalRun failed: %v", err)
	}

	dispatcher := NewGroupDispatcher(controller)
	dispatcher.SetPollInterval(10 * time.Millisecond)
	dispatcher.SetRunPollInterval(10 * time.Millisecond)
	dispatchCtx, cancel := context.WithCancel(context.Background())
	defer cancel()
	go dispatcher.Start(dispatchCtx)

	// This bundle run is stable in isolation but can take materially longer under
	// full Linux CI package load, especially while the dispatcher drains all 23 items.
	deadline := time.Now().Add(30 * time.Second)
	for time.Now().Before(deadline) {
		report, err := controller.GetGroupReport(context.Background(), evalRun.GroupID)
		if err == nil && report != nil && report.Group != nil {
			switch report.Group.Status {
			case RunGroupStatusCompleted, RunGroupStatusPartial, RunGroupStatusFailed, RunGroupStatusCancelled:
				if len(report.Scorecards) == 23 {
					goto reportReady
				}
			}
		}
		time.Sleep(50 * time.Millisecond)
	}
	t.Fatal("timed out waiting for pinchbench bundle eval terminal state")

reportReady:
	report, err := controller.GetGroupReport(context.Background(), evalRun.GroupID)
	if err != nil {
		t.Fatalf("GetGroupReport failed: %v", err)
	}
	if len(report.Items) != 23 {
		t.Fatalf("report items len = %d, want 23", len(report.Items))
	}
	if len(report.Scorecards) != 23 {
		t.Fatalf("report scorecards len = %d, want 23", len(report.Scorecards))
	}
	if len(report.LinkedRuns) != 23 {
		t.Fatalf("report linked runs len = %d, want 23", len(report.LinkedRuns))
	}
	if !observedSeededWorkspace {
		t.Fatal("expected seeded workspace fixture to be visible to the driver")
	}
}

func TestController_ImportDatasetBundleReusesMatchingVersionAndUpdatesEvalSpec(t *testing.T) {
	controller := newTestController(t)

	firstReq := testDatasetBundleImportRequest(t, "bundle-dataset", "v1", "bundle-profile", false)
	firstReq.MakeActive = true
	first, err := controller.ImportDatasetBundle(context.Background(), firstReq)
	if err != nil {
		t.Fatalf("ImportDatasetBundle(first) failed: %v", err)
	}

	secondReq := testDatasetBundleImportRequest(t, "bundle-dataset", "v1", "bundle-profile", false)
	secondReq.MakeActive = true
	secondReq.EvalSpecs[0].Profile = "bundle-profile-updated"
	secondReq.EvalSpecs[0].Metadata = map[string]interface{}{
		"lane":    "default",
		"updated": "true",
	}
	second, err := controller.ImportDatasetBundle(context.Background(), secondReq)
	if err != nil {
		t.Fatalf("ImportDatasetBundle(second) failed: %v", err)
	}

	if second.Dataset.ID != first.Dataset.ID {
		t.Fatalf("dataset id = %q, want %q", second.Dataset.ID, first.Dataset.ID)
	}
	if second.DatasetVersion.ID != first.DatasetVersion.ID {
		t.Fatalf("dataset version id = %q, want %q", second.DatasetVersion.ID, first.DatasetVersion.ID)
	}
	if len(second.EvalSpecs) != 1 || len(first.EvalSpecs) != 1 {
		t.Fatalf("eval spec counts first=%d second=%d, want 1/1", len(first.EvalSpecs), len(second.EvalSpecs))
	}
	if second.EvalSpecs[0].ID != first.EvalSpecs[0].ID {
		t.Fatalf("eval spec id = %q, want %q", second.EvalSpecs[0].ID, first.EvalSpecs[0].ID)
	}
	if second.EvalSpecs[0].Profile != "bundle-profile-updated" {
		t.Fatalf("updated profile = %q, want bundle-profile-updated", second.EvalSpecs[0].Profile)
	}
	if got := metadataString(second.EvalSpecs[0].Metadata, "updated"); got != "true" {
		t.Fatalf("updated metadata = %q, want true", got)
	}

	specs, err := controller.ListEvalSpecs(context.Background(), EvalSpecFilter{
		OwnerUserID: "bundle-owner",
		DatasetID:   first.Dataset.ID,
		Limit:       10,
	})
	if err != nil {
		t.Fatalf("ListEvalSpecs failed: %v", err)
	}
	if len(specs) != 1 {
		t.Fatalf("eval specs len = %d, want 1", len(specs))
	}
}

